function initialsOf(name) {
  return name
    .split(/[\s-]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase())
    .slice(0, 2)
    .join("");
}

export const AI_CHARACTERS = Object.freeze(
  ROSTER.map((character) => Object.freeze({ ...character, initials: character.initials ?? initialsOf(character.name) })),
);

const BY_ID = new Map(AI_CHARACTERS.map((character) => [character.id, character]));

export function getCharacter(id) {
  return BY_ID.get(id) ?? null;
}

// Pick `count` distinct characters at random, skipping any ids in `exclude`.
export function pickCharacters(count, { exclude = [], rng = Math.random } = {}) {
  const excluded = new Set(exclude);
  const pool = AI_CHARACTERS.filter((character) => !excluded.has(character.id));
  if (!Number.isInteger(count) || count < 0) throw new RangeError(`Invalid character count: ${count}`);
  if (count > pool.length) throw new RangeError(`Cannot pick ${count} characters; only ${pool.length} available.`);
  for (let i = pool.length - 1; i > 0; i -= 1) {
    const j = Math.floor(rng() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, count);
}
